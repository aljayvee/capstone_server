/**
 * Trains the reason-suggestion network on ml/exception-reasons/dataset.csv.
 *
 *   npx tsx scripts/exception-reasons/train.ts
 *
 * Writes two files:
 *   src/services/patterns/exceptionReasonWeights.ts  the trained model the API serves
 *   ml/exception-reasons/report.json                 how well it did on rows it never saw
 *
 * The rows are split 70/15/15 per reason. The network learns from the first
 * part by backpropagation, the second part decides when to stop (the epoch with
 * the lowest validation loss is kept), and the third part is only ever used
 * once, at the end, to measure it. The settings live in config.ts.
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  countParameters,
  createNetwork,
  describeNetwork,
  evaluate,
  seededRandom,
  train,
  type Network,
} from "../../src/services/patterns/neuralNetwork.js";
import {
  CONFIDENCE_THRESHOLD,
  FEATURE_NAMES,
  REASONS,
  REASON_CODES,
  type TrainedReasonModel,
} from "../../src/services/patterns/exceptionReasonModel.js";
import { PRODUCTION } from "./config.js";
import { loadRows, majorityBaseline, measure, round, stratifiedSplit, toSample, ML_DIR } from "./evaluation.js";

const here = dirname(fileURLToPath(import.meta.url));
const REPORT = resolve(ML_DIR, "report.json");
const WEIGHTS = resolve(here, "../../src/services/patterns/exceptionReasonWeights.ts");

function writeWeights(model: TrainedReasonModel) {
  const r6 = (xs: number[]) => xs.map((x) => round(x, 6));
  const network: Network = {
    ...model.network,
    layers: model.network.layers.map((l) => ({ ...l, weights: r6(l.weights), biases: r6(l.biases) })),
  };
  const source = `// GENERATED by scripts/exception-reasons/train.ts. Do not edit by hand: retrain.
//
// A ${describeNetwork(model.network)} network (${countParameters(model.network)} weights and biases) trained by
// backpropagation on ml/exception-reasons/dataset.csv. Held-out test: ${(model.metrics.testAccuracy * 100).toFixed(1)}% accurate overall;
// ${(model.metrics.coverageAtThreshold * 100).toFixed(1)}% of rows clear the ${CONFIDENCE_THRESHOLD} threshold, and those are right
// ${(model.metrics.accuracyWhenConfident * 100).toFixed(1)}% of the time. Full figures in ml/exception-reasons/report.json.
import type { TrainedReasonModel } from "./exceptionReasonModel.js";

export const EXCEPTION_REASON_MODEL: TrainedReasonModel = ${JSON.stringify({ ...model, network })};
`;
  writeFileSync(WEIGHTS, source);
}

function main() {
  const labelled = loadRows();
  const { trainSet, valSet, testSet } = stratifiedSplit(labelled.map(toSample));

  const initial = createNetwork(
    { inputs: FEATURE_NAMES.length, hidden: PRODUCTION.hidden, outputs: REASON_CODES.length, activation: PRODUCTION.activation },
    seededRandom(PRODUCTION.seed)
  );
  const started = Date.now();
  const { network, history, bestEpoch } = train(initial, trainSet, valSet, PRODUCTION);
  const seconds = (Date.now() - started) / 1000;

  const test = measure(network, testSet);
  const trainFit = evaluate(network, trainSet);
  const trainedAt = new Date().toISOString();

  const model: TrainedReasonModel = {
    version: `exception-reasons-${trainedAt.slice(0, 10)}`,
    trainedAt,
    featureNames: [...FEATURE_NAMES],
    classes: [...REASON_CODES],
    network,
    metrics: {
      trainingRows: trainSet.length,
      testRows: testSet.length,
      testAccuracy: test.accuracy,
      coverageAtThreshold: test.coverageAtThreshold,
      accuracyWhenConfident: test.accuracyWhenConfident,
    },
  };
  writeWeights(model);

  const report = {
    model: model.version,
    trainedAt,
    dataset: {
      file: "ml/exception-reasons/dataset.csv",
      rows: labelled.length,
      sources: Object.fromEntries(
        [...new Set(labelled.map((l) => l.source))].map((s) => [s, labelled.filter((l) => l.source === s).length])
      ),
      split: { train: trainSet.length, validation: valSet.length, test: testSet.length },
    },
    architecture: {
      network: describeNetwork(network),
      parameters: countParameters(network),
      outputs: `${REASON_CODES.length} softmax, masked to the exception's kind`,
      loss: "cross-entropy + L2",
      ...PRODUCTION,
    },
    training: {
      epochsRun: history.length,
      bestEpoch,
      seconds,
      trainAccuracy: round(trainFit.accuracy),
      bestValidationLoss: round(history[bestEpoch - 1].valLoss),
      validationAccuracy: round(history[bestEpoch - 1].valAccuracy),
    },
    threshold: CONFIDENCE_THRESHOLD,
    test: {
      ...test,
      majorityBaselineAccuracy: majorityBaseline(trainSet, testSet),
    },
    features: FEATURE_NAMES,
    reasons: REASONS.map((r) => ({ code: r.code, kind: r.kind })),
  };
  writeFileSync(REPORT, JSON.stringify(report, null, 2) + "\n");

  console.log(`${describeNetwork(network)}: trained on ${trainSet.length} rows in ${seconds.toFixed(1)}s, best epoch ${bestEpoch}/${history.length}.`);
  console.log(`Test accuracy ${(test.accuracy * 100).toFixed(1)}% (always-commonest baseline ${(report.test.majorityBaselineAccuracy * 100).toFixed(1)}%).`);
  console.log(
    `At ${CONFIDENCE_THRESHOLD}: suggests for ${(test.coverageAtThreshold * 100).toFixed(1)}% of rows, right ${(test.accuracyWhenConfident * 100).toFixed(1)}% of the time.`
  );
  for (const k of test.byKind) {
    console.log(
      `  ${k.kind.padEnd(20)} acc ${(k.accuracy * 100).toFixed(0).padStart(3)}%  covered ${(k.coverageAtThreshold * 100).toFixed(0).padStart(3)}%  right-when-sure ${(k.accuracyWhenConfident * 100).toFixed(0).padStart(3)}%`
    );
  }
}

main();
